--процедура удаления брони по истечению срока брони 

--DROP PROCEDURE IF EXISTS public.очистить_просроченные_брони();

CREATE OR REPLACE PROCEDURE public.очистить_просроченные_брони()
LANGUAGE plpgsql
AS $procedure$
BEGIN
    -- 1. Меняем статус просроченных броней на 4 ("Бронь отменена")
    UPDATE public.билет б
    SET id_статуса_билета = 4 
    FROM public.место_события мс
    JOIN public.событие с ON мс.id_события = с.id_события
    WHERE б.id_места_события = мс.id_места_события
      AND б.id_статуса_билета = 1 -- Только те, что "Забронированы"
      AND now() > б.дата_создания + (с.срок_брони_мин || ' minutes')::INTERVAL;

    -- 2. Удаляем эти места из таблицы занятости, чтобы они снова стали доступны
    DELETE FROM public.занятое_место зм
    USING public.билет б
    WHERE зм.id_места_события = б.id_места_события
      AND б.id_статуса_билета = 4 -- Удаляем места только тех билетов, которые только что отменились
      AND now() > б.дата_создания + (
          SELECT срок_брони_мин FROM public.событие с 
          JOIN public.место_события мс ON с.id_события = мс.id_события
          WHERE мс.id_места_события = б.id_места_события
      ) * interval '1 minute';
      
    -- Сообщаем в консоль, что работа выполнена
    RAISE NOTICE 'Очистка просроченных броней завершена.';
END;
$procedure$;