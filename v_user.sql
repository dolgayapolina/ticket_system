--Афиша событий - собития, дата который сегодня или в будущем 
DROP VIEW IF EXISTS public.v_афиша_событий;

CREATE
VIEW v_афиша_событий AS (
SELECT
	событие.id_события AS "ID события",
	событие.название AS "Событие",
	тип_мероприятия.название AS "Тип мероприятия",
	событие.дата_начала AS "Дата",
	площадка.город AS "Город",
	площадка.название AS "Площадка"
FROM
	public.событие
JOIN public.схема_зала ON public.событие.id_схемы = public.схема_зала.id_схемы
JOIN public.зал ON public.схема_зала.id_зала = public.зал.id_зала
JOIN public.площадка ON public.зал.id_площадки = public.площадка.id_площадки
JOIN public.тип_мероприятия ON public.событие.id_типа_мероприятия = public.тип_мероприятия.id_типа_мероприятия
WHERE событие.дата_начала >= CURRENT_DATE  
	); 


--Схема зала для события 
--DROP VIEW IF EXISTS public.v_схема_зала_события;
CREATE VIEW v_схема_зала_события AS (
SELECT 
место_события.id_события AS "ID события",
место.номер_места AS "Номер места",
место.номер_ряда AS "Номер ряда",
зона.название AS "Зона",
CASE 
	WHEN занятое_место.id_места_события IS NOT NULL THEN 'Занято'
	ELSE 'Свободно'
END AS "Статус места"
FROM public.место_события
JOIN public.место ON public.место_события.id_места = public.место.id_места
JOIN public.зона ON public.место.id_зоны = public.зона.id_зоны
LEFT JOIN public.занятое_место ON public.место_события.id_места_события = public.занятое_место.id_места_события
);

--Свободные места на событие 
--DROP VIEW IF EXISTS public.v_свободные_места;
CREATE VIEW v_свободные_места AS (
SELECT 
место_события.id_события AS "ID события",        
место_события.id_места_события AS "ID места на событии",
место.номер_места AS "Номер места",
место.номер_ряда AS "Номер ряда",
зона.название AS "Зона" 
FROM public.место_события
JOIN public.место ON public.место_события.id_места = public.место.id_места
JOIN public.зона ON public.место.id_зоны = public.зона.id_зоны
LEFT JOIN public.занятое_место ON public.место_события.id_места_события = public.занятое_место.id_места_события
WHERE занятое_место.id_места_события IS NULL
);